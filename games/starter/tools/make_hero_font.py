#!/usr/bin/env python3
"""
make_hero_font.py - the starter's large "hero text" font (HELLO / WORLD).

The starter flashes HELLO / WORLD with the engine's proportional big-font
routines (engine/graphics/bigfont.asm), the same ones Duck Rescue's GAME OVER
screen uses. Duck Rescue's Michroma font is sized for its placards: at that
size "WORLD" is 336 pixels wide and does not fit the engine's 320-pixel
screen. This script makes a copy scaled to SCALE (80%) for the starter.

Input  (Duck Rescue's font, read only):
    engine/graphics/michroma_font_data.asm      - MICHROMA_H, offsets, widths, char map
    games/duck_rescue/assets/font/michroma_font.bin
Output (the starter's own copy):
    games/starter/assets/font/hero_font.bin
    games/starter/include/hero_font_data.asm

The output uses the same label names as michroma_font_data.asm
(MichromaFont, MichromaOffsets, MichromaWidths, MichromaCharMap, MICHROMA_H,
MICHROMA_GLYPHS), so bigfont.asm works with either file unchanged. A game
includes one of the two, never both.

Each glyph is scaled with area averaging and thresholded back to one bit;
its new width is the scaled cell width rounded up to whole bytes, which
keeps the letter spacing. Michroma is licensed under the SIL Open Font
License 1.1; this bitmap is derived from Duck Rescue's rendering of it.

Run from the repository root:
    python games/starter/tools/make_hero_font.py
"""

import math
import re
import sys
from pathlib import Path

from PIL import Image

SCALE = 0.8
THRESHOLD = 128                       # 0..255 coverage at which a pixel is set

SRC_ASM = Path("engine/graphics/michroma_font_data.asm")
SRC_BIN = Path("games/duck_rescue/assets/font/michroma_font.bin")
DST_BIN = Path("games/starter/assets/font/hero_font.bin")
DST_ASM = Path("games/starter/include/hero_font_data.asm")


def read_table(text, label):
    """Numbers in the dc.w / dc.b lines that follow `label:`."""
    m = re.search(rf"^{label}:\s*\n((?:\s+dc\.[bw].*\n)+)", text, re.M)
    if not m:
        raise SystemExit(f"error: {label} not found in {SRC_ASM}")
    return [int(v) for v in re.findall(r"\d+", re.sub(r"dc\.[bw]", "", m.group(1)))]


def read_equate(text, name):
    m = re.search(rf"^{name}\s*=\s*(\d+)", text, re.M)
    if not m:
        raise SystemExit(f"error: {name} not found in {SRC_ASM}")
    return int(m.group(1))


def glyph_image(data, offset, width_bytes, height):
    """One glyph as an 8-bit image (255 = ink)."""
    im = Image.new("L", (width_bytes * 8, height), 0)
    px = im.load()
    for y in range(height):
        for b in range(width_bytes):
            v = data[offset + y * width_bytes + b]
            for bit in range(8):
                if v & (0x80 >> bit):
                    px[b * 8 + bit, y] = 255
    return im


def image_to_bytes(im, width_bytes):
    out = bytearray()
    px = im.load()
    for y in range(im.height):
        for b in range(width_bytes):
            v = 0
            for bit in range(8):
                x = b * 8 + bit
                if x < im.width and px[x, y] >= THRESHOLD:
                    v |= 0x80 >> bit
            out.append(v)
    return bytes(out)


def main() -> int:
    if not SRC_ASM.is_file() or not SRC_BIN.is_file():
        print("error: run from the repository root (needs the engine and Duck Rescue font files)",
              file=sys.stderr)
        return 1
    text = SRC_ASM.read_text(encoding="utf-8")
    src_h = read_equate(text, "MICHROMA_H")
    glyphs = read_equate(text, "MICHROMA_GLYPHS")
    offsets = read_table(text, "MichromaOffsets")
    widths = read_table(text, "MichromaWidths")
    charmap = read_table(text, "MichromaCharMap")
    data = SRC_BIN.read_bytes()
    assert len(offsets) == glyphs and len(widths) == glyphs and len(charmap) == 256

    new_h = round(src_h * SCALE)
    out = bytearray()
    new_offsets, new_widths = [], []
    for g in range(glyphs):
        src = glyph_image(data, offsets[g], widths[g], src_h)
        new_px = max(1, round(widths[g] * 8 * SCALE))
        wb = math.ceil(new_px / 8)
        small = src.resize((new_px, new_h), Image.Resampling.BOX)
        new_offsets.append(len(out))
        new_widths.append(wb)
        out += image_to_bytes(small, wb)

    DST_BIN.parent.mkdir(parents=True, exist_ok=True)
    DST_BIN.write_bytes(out)

    def rows(values, per_row, kind):
        return "\n".join(f"    {kind}    " + ",".join(str(v) for v in values[i:i + per_row])
                         for i in range(0, len(values), per_row))

    asm = f"""; AUTO-GENERATED by games/starter/tools/make_hero_font.py - DO NOT HAND-EDIT.
; Duck Rescue's Michroma font (engine/graphics/michroma_font_data.asm) scaled to
; {round(SCALE * 100)}% so that "WORLD" fits the engine's 320-pixel screen. Michroma is
; licensed under the SIL Open Font License 1.1.
;
; Same labels as michroma_font_data.asm, so engine/graphics/bigfont.asm draws
; this font unchanged. Include one of the two files, never both.
; Charset: A-Z, 0-9, space ({glyphs} glyphs).
;
; MichromaFont       - glyph bitmaps, MICHROMA_H rows each, concatenated;
;                      1 bitplane, MSB = leftmost pixel.
; MichromaOffsets    - byte offset of each glyph within MichromaFont (word).
; MichromaWidths     - byte width (bytes/row) of each glyph (word).
; MichromaCharMap    - 256 bytes, ASCII code -> glyph index (space if unmapped).

MICHROMA_H      =     {new_h}
MICHROMA_GLYPHS =     {glyphs}

MichromaFont:
    incbin  'assets/font/hero_font.bin'
    even

MichromaOffsets:
{rows(new_offsets, 8, "dc.w")}

MichromaWidths:
{rows(new_widths, 8, "dc.w")}

MichromaCharMap:
{rows(charmap, 16, "dc.b")}
    even
"""
    DST_ASM.write_text(asm, encoding="utf-8", newline="\n")

    def width(s):
        return sum(new_widths[charmap[ord(c)]] for c in s)
    print(f"hero font: {glyphs} glyphs, {new_h} rows, {len(out)} bytes -> {DST_BIN}, {DST_ASM}")
    print(f"  HELLO = {width('HELLO') * 8} px, WORLD = {width('WORLD') * 8} px (screen 320 px)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
